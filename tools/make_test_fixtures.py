#!/usr/bin/env python3
"""Regenerates firmware/tests/jpeg_fixture.h (needs Pillow)."""
import io
import pathlib

from PIL import Image, ImageDraw


def jpg(w, h, color, quality=90, subsampling=2, progressive=False, quadrant=True):
    im = Image.new("RGB", (w, h), color)
    if quadrant:
        ImageDraw.Draw(im).rectangle([0, 0, w // 2 - 1, h // 2 - 1], fill=(255, 255, 255))
    buf = io.BytesIO()
    im.save(buf, "JPEG", quality=quality, subsampling=subsampling, progressive=progressive)
    return buf.getvalue()


def c_array(name, data):
    rows = ["    " + ", ".join(f"0x{x:02x}" for x in data[i:i + 16]) + "," for i in range(0, len(data), 16)]
    return f"static const unsigned char {name}[] = {{\n" + "\n".join(rows) + "\n};\n"


HEADER = """/* Generated by tools/make_test_fixtures.py - do not edit. */
/* key: 96x96 red with a white top-left quadrant (4:2:0). strip: 200x100 blue, white quadrant (4:4:4).
   wrong: 72x72. progressive: 96x96 progressive JPEG, which the decoder does not support. */
"""

out = pathlib.Path(__file__).resolve().parent.parent / "firmware" / "tests" / "jpeg_fixture.h"
out.write_text(
    HEADER
    + c_array("jpeg_key_96", jpg(96, 96, (200, 30, 30)))
    + c_array("jpeg_strip_200x100", jpg(200, 100, (20, 60, 220), subsampling=0))
    + c_array("jpeg_wrong_72", jpg(72, 72, (0, 255, 0)))
    + c_array("jpeg_progressive_96", jpg(96, 96, (1, 2, 3), progressive=True, quadrant=False))
)
print("wrote", out)
